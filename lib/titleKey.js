// 책 제목을 견주기 위한 열쇠
//
// 같은 책인데 표기가 조금씩 다르게 온다. 추천에서 실제로 겪은 것:
//
//   서재: 『총 균 쇠』   ←→   추천: 『총, 균, 쇠』
//
// 띄어쓰기만 지우고 견주면 이 둘이 다른 책이 되어, 이미 서재에 있는 책이
// 다시 추천됐다. 그래서 **가운뎃점·쉼표 같은 이음표까지 지우고** 견준다.
//
// 글자 자체는 남긴다 — 너무 많이 지우면 서로 다른 책이 같은 책으로 묶인다.
//
// 서버(app/api/recommend)와 화면(components/RecommendList)이 같은 기준으로
// 걸러내야 해서 한곳에 두었다. 한쪽만 고치면 또 어긋난다.

/** 제목·지은이를 견주기 위해 납작하게 만든다. 띄어쓰기·이음표·대소문자를 무시한다. */
export function titleKey(value) {
  return String(value ?? '')
    .replace(/\s+/g, '')
    // 제목 사이에 끼는 이음표들. 있는 쪽과 없는 쪽이 같은 책일 때가 많다.
    .replace(/[,，、·・‧.。:：;；!！?？\-–—_/／]/g, '')
    .toLowerCase();
}
